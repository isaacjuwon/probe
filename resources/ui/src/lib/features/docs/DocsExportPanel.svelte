<script lang="ts">
  import type { EndpointsState } from '$lib/features/endpoints/endpoints.state.svelte';
  import { ScrollArea } from '$lib/components/ui/scroll-area';
  import { Button } from '$lib/components/ui/button';
  import {
    BookOpen,
    Download,
    FileJson,
    FolderArchive,
    Check,
    Layers,
    FileCode,
    Sparkles,
  } from '@lucide/svelte';

  export interface Props {
    readonly endpointsState: EndpointsState;
  }

  const { endpointsState }: Props = $props();

  let exportFeedback = $state<string | null>(null);

  const endpoints = $derived(endpointsState.endpoints);

  const methodCounts = $derived.by(() => {
    const counts: Record<string, number> = {
      GET: 0,
      POST: 0,
      PUT: 0,
      PATCH: 0,
      DELETE: 0,
    };
    for (const ep of endpoints) {
      const m = ep.method.toUpperCase();
      if (counts[m] !== undefined) {
        counts[m]++;
      } else {
        counts[m] = 1;
      }
    }
    return counts;
  });

  function downloadJson(filename: string, data: unknown): void {
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(data, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute('href', dataStr);
    downloadAnchor.setAttribute('download', filename);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  }

  function exportOpenApi(): void {
    const paths: Record<string, Record<string, unknown>> = {};

    for (const ep of endpoints) {
      const path = '/' + ep.uri.replace(/^\//, '');
      if (!paths[path]) {
        paths[path] = {};
      }

      const methodKey = ep.method.toLowerCase();
      paths[path][methodKey] = {
        summary: ep.name || ep.uri,
        description: ep.description || `Generated by Probe for ${ep.method} ${ep.uri}`,
        operationId: `${ep.method.toLowerCase()}_${ep.uri.replace(/[^a-zA-Z0-9]/g, '_')}`,
        responses: {
          '200': {
            description: 'Successful response',
          },
        },
      };
    }

    const openApiDoc = {
      openapi: '3.1.0',
      info: {
        title: 'Probe API Specification',
        version: '1.0.0',
        description: 'Auto-generated API specification from Laravel route inspection with Probe.',
      },
      paths,
    };

    downloadJson(`probe-openapi-spec-${new Date().toISOString().slice(0, 10)}.json`, openApiDoc);
    exportFeedback = 'OpenAPI 3.1 Spec downloaded!';
    setTimeout(() => (exportFeedback = null), 2500);
  }

  function exportPostman(): void {
    const items = endpoints.map((ep) => {
      const origin = typeof window !== 'undefined' ? window.location.origin : 'http://localhost';
      const cleanUri = ep.uri.replace(/^\//, '');

      return {
        name: ep.name || ep.uri,
        request: {
          method: ep.method,
          header: Object.entries(ep.headers || {}).map(([key, value]) => ({
            key,
            value,
            type: 'text',
          })),
          url: {
            raw: `${origin}/${cleanUri}`,
            protocol: origin.startsWith('https') ? 'https' : 'http',
            host: [origin.replace(/^https?:\/\//, '')],
            path: cleanUri.split('/'),
          },
          description: ep.description || '',
        },
      };
    });

    const postmanDoc = {
      info: {
        name: 'Probe API Collection',
        _postman_id: 'probe-' + Date.now(),
        description: 'Exported from Probe for Laravel',
        schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
      },
      item: items,
    };

    downloadJson(`probe-postman-collection-${new Date().toISOString().slice(0, 10)}.json`, postmanDoc);
    exportFeedback = 'Postman Collection downloaded!';
    setTimeout(() => (exportFeedback = null), 2500);
  }
</script>

<div class="flex flex-col h-full bg-card/30">
  <!-- Header -->
  <div class="p-3 border-b border-border space-y-2.5">
    <div class="flex items-center justify-between">
      <span class="text-xs font-semibold uppercase tracking-wider text-muted-foreground flex items-center gap-1.5">
        <BookOpen class="h-3.5 w-3.5 text-primary" />
        API Docs & Exporters
      </span>
      <span class="text-[10px] font-mono px-1.5 py-0.5 rounded bg-muted text-muted-foreground font-semibold">
        {endpoints.length} routes
      </span>
    </div>

    {#if exportFeedback}
      <div class="p-2 rounded bg-emerald-500/10 border border-emerald-500/30 text-emerald-500 text-xs flex items-center gap-1.5 animate-in fade-in duration-200">
        <Check class="h-3.5 w-3.5" />
        <span>{exportFeedback}</span>
      </div>
    {/if}

    <!-- Endpoint stats by HTTP method -->
    <div class="grid grid-cols-5 gap-1 text-center">
      <div class="p-1.5 rounded bg-background/60 border border-border/50">
        <div class="text-[9px] text-blue-500 font-bold">GET</div>
        <div class="text-xs font-bold font-mono">{methodCounts.GET ?? 0}</div>
      </div>
      <div class="p-1.5 rounded bg-background/60 border border-border/50">
        <div class="text-[9px] text-emerald-500 font-bold">POST</div>
        <div class="text-xs font-bold font-mono">{methodCounts.POST ?? 0}</div>
      </div>
      <div class="p-1.5 rounded bg-background/60 border border-border/50">
        <div class="text-[9px] text-amber-500 font-bold">PUT</div>
        <div class="text-xs font-bold font-mono">{methodCounts.PUT ?? 0}</div>
      </div>
      <div class="p-1.5 rounded bg-background/60 border border-border/50">
        <div class="text-[9px] text-orange-500 font-bold">PATCH</div>
        <div class="text-xs font-bold font-mono">{methodCounts.PATCH ?? 0}</div>
      </div>
      <div class="p-1.5 rounded bg-background/60 border border-border/50">
        <div class="text-[9px] text-red-500 font-bold">DEL</div>
        <div class="text-xs font-bold font-mono">{methodCounts.DELETE ?? 0}</div>
      </div>
    </div>
  </div>

  <!-- Exporters Section -->
  <ScrollArea class="flex-1 p-3 space-y-3">
    <!-- OpenAPI Exporter Card -->
    <div class="p-3 rounded-lg bg-background/70 border border-border/70 space-y-2 hover:border-primary/40 transition-colors">
      <div class="flex items-center gap-2">
        <div class="p-1.5 rounded-md bg-primary/10 text-primary">
          <FileCode class="h-4 w-4" />
        </div>
        <div>
          <h4 class="text-xs font-semibold text-foreground">OpenAPI 3.1 Spec</h4>
          <p class="text-[11px] text-muted-foreground">Standard OpenAPI JSON definition</p>
        </div>
      </div>
      <p class="text-[11px] text-muted-foreground/90">
        Exports all {endpoints.length} discovered endpoints with operations, parameters, and routes formatted for Swagger UI, Redoc, or API gateways.
      </p>
      <Button
        variant="outline"
        size="sm"
        onclick={exportOpenApi}
        class="w-full h-7 text-xs font-medium gap-1.5 bg-background/50 hover:bg-background"
      >
        <Download class="h-3.5 w-3.5 text-primary" />
        <span>Download OpenAPI 3.1 JSON</span>
      </Button>
    </div>

    <!-- Postman Collection Exporter Card -->
    <div class="p-3 rounded-lg bg-background/70 border border-border/70 space-y-2 hover:border-primary/40 transition-colors">
      <div class="flex items-center gap-2">
        <div class="p-1.5 rounded-md bg-orange-500/10 text-orange-500">
          <FileJson class="h-4 w-4" />
        </div>
        <div>
          <h4 class="text-xs font-semibold text-foreground">Postman Collection v2.1</h4>
          <p class="text-[11px] text-muted-foreground">Import directly into Postman or Bruno</p>
        </div>
      </div>
      <p class="text-[11px] text-muted-foreground/90">
        Ready-to-use Postman collection JSON file with requests, headers, and parameterized URLs.
      </p>
      <Button
        variant="outline"
        size="sm"
        onclick={exportPostman}
        class="w-full h-7 text-xs font-medium gap-1.5 bg-background/50 hover:bg-background"
      >
        <Download class="h-3.5 w-3.5 text-orange-500" />
        <span>Download Postman JSON</span>
      </Button>
    </div>

    <!-- Scribe Sync info -->
    <div class="p-3 rounded-lg bg-muted/40 border border-border/50 space-y-1.5 text-xs text-muted-foreground">
      <div class="font-semibold text-foreground flex items-center gap-1.5">
        <Sparkles class="h-3.5 w-3.5 text-primary" />
        <span>Scribe Documentation</span>
      </div>
      <p class="text-[11px]">
        Probe automatically synchronizes with Scribe metadata when installed in your Laravel app:
      </p>
      <pre class="bg-background/80 p-1.5 rounded font-mono text-[10px] text-foreground border border-border/40 select-all">php artisan probe:scribe-sync</pre>
    </div>
  </ScrollArea>
</div>
